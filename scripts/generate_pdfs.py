class MedicalPDF(FPDF):
    """Custom PDF class with Chinese font support."""

    def __init__(self):
        super().__init__()
        self.add_font("CJK", fname=FONT_PATH)
        self.set_auto_page_break(auto=True, margin=15)

    def header_block(self, text, size=16):
        self.set_font("CJK", size=size)
        self.multi_cell(0, 10, text, align="C")
        self.ln(4)

    def section_title(self, text):
        self.set_font("CJK", size=11)
        self.set_fill_color(230, 230, 230)
        self.multi_cell(0, 8, text, fill=True)
        self.ln(1)

    def body_text(self, text):
        self.set_font("CJK", size=10)
        self.multi_cell(0, 6, text)
        self.ln(1)

    def footer_text(self, text):
        self.set_font("CJK", size=9)
        self.set_text_color(100, 100, 100)
        self.multi_cell(0, 5, text)
        self.set_text_color(0, 0, 0)

    def table(self, headers, rows, col_widths, font_size=9):
        """Draw a simple table. Returns current Y."""
        self.set_font("CJK", size=font_size)
        # Header
        self.set_fill_color(200, 200, 200)
        for i, (h, w) in enumerate(zip(headers, col_widths)):
            self.cell(w, 8, h, border=1, fill=True, align="C")
        self.ln()
        # Rows
        for row in rows:
            for i, (cell, w) in enumerate(zip(row, col_widths)):
                self.cell(w, 7, str(cell), border=1, align="C")
            self.ln()
        self.ln(3)

    def info_table(self, pairs):
        """Draw a key-value info table with 2 columns per row."""
        self.set_font("CJK", size=10)
        keys = list(pairs.keys())
        vals = list(pairs.values())
        n = len(keys)
        col_w = (self.w - 2 * self.l_margin) / 4
        for i in range(0, n, 2):
            for j in range(2):
                idx = i + j
                if idx < n:
                    self.set_font("CJK", size=10)
                    self.cell(col_w, 7, keys[idx], border=1, align="C")
                    self.set_font("CJK", size=10)
                    self.cell(col_w, 7, str(vals[idx]), border=1, align="C")
            self.ln()
        self.ln(3)


def add_page_number(pdf):
    """Annotate page number via footer callback override."""
    pdf.set_y(-15)
    pdf.set_font("CJK", size=8)
    pdf.set_text_color(128, 128, 128)
    pdf.cell(0, 10, f"第 {pdf.page_no()} 页", align="C")
    pdf.set_text_color(0, 0, 0)


